static bool
csane_hint_same(Token *a, Token *b) {
    return a->kind == TOKEN_IDENT && b->kind == TOKEN_IDENT
           && a->len == b->len && !memcmp64(a->text, b->text, a->len);
}

static void
csane_hint_add(CsaneTypeHints *hints, int32 token,
               enum CsaneTypeHintKind kind) {
    Token *candidate = &hints->tokens->tokens[token];
    if (candidate->kind != TOKEN_IDENT) {
        return;
    }
    for (int32 i = 0; i < hints->count; i += 1) {
        CsaneTypeHint *hint = &hints->items[i];
        if (hint->kind == kind && hint->macro_close < 0
            && csane_hint_same(candidate,
                               &hints->tokens->tokens[hint->token])) {
            return;
        }
    }
    if (hints->count == hints->capacity) {
        int32 next = hints->capacity ? hints->capacity*2 : 32;
        hints->items = realloc2(hints->items, hints->capacity, next,
                                SIZEOF(*hints->items));
        hints->capacity = next;
    }
    hints->items[hints->count] = (CsaneTypeHint){
        .token = token,
        .macro_close = -1,
        .kind = kind,
    };
    hints->count += 1;
    return;
}

bool
csane_type_hints_has(CsaneTypeHints *hints, Token *token,
                     enum CsaneTypeHintKind kind) {
    if (hints == NULL || hints->tokens == NULL || token == NULL
        || token->kind != TOKEN_IDENT) {
        return false;
    }
    for (int32 i = 0; i < hints->count; i += 1) {
        CsaneTypeHint *hint = &hints->items[i];
        if (hint->kind == kind && hint->macro_close < 0
            && csane_hint_same(token, &hints->tokens->tokens[hint->token])) {
            return true;
        }
    }
    return false;
}

bool
csane_type_hints_typedef(CsaneTypeHints *hints, Token *token) {
    return csane_type_hints_has(hints, token, CSANE_TYPE_HINT_TYPEDEF);
}

bool
csane_type_hints_tag(CsaneTypeHints *hints, Token *token) {
    return csane_type_hints_has(hints, token, CSANE_TYPE_HINT_TAG);
}

static bool
csane_hint_word(Token *token, char *word, int32 word_len) {
    return token->kind == TOKEN_IDENT && TOKEN_IS(token, word, word_len);
}

static bool
csane_hint_aggregate(Token *token) {
    return csane_hint_word(token, STRLIT("struct"))
           || csane_hint_word(token, STRLIT("union"))
           || csane_hint_word(token, STRLIT("enum"));
}

/* Preserve typedef names generated by function-like macros, e.g.
 * typedef struct CAT(NAME, _Data) { ... } CAT(NAME, _Data);
 * Comparing the complete invocation avoids classifying arbitrary call
 * expressions as types merely because their callee is uppercase. */
static void
csane_hint_macro_typedef(CsaneTypeHints *hints, CsaneTokenView *view,
                         int32 close) {
    Tokenization *tokens = view->tokens;
    int32 open = csane_tokens_match(view, close);
    int32 name;

    if (open < 0 || !TOKEN_IS(&tokens->tokens[open], "(")) {
        return;
    }
    name = csane_tokens_previous(view, open);
    if (name < view->range.first
        || !csane_token_macro_name(&tokens->tokens[name])) {
        return;
    }
    for (int32 i = 0; i < hints->count; i += 1) {
        CsaneTypeHint *hint = &hints->items[i];
        if (hint->token == name && hint->macro_close == close) {
            return;
        }
    }
    if (hints->count == hints->capacity) {
        int32 previous = hints->capacity;
        int32 next = previous ? previous*2 : 32;
        if (previous == 0) {
            hints->items = malloc2(next*SIZEOF(*hints->items));
        } else {
            hints->items = realloc2(hints->items, previous, next,
                                    SIZEOF(*hints->items));
        }
        hints->capacity = next;
    }
    hints->items[hints->count] = (CsaneTypeHint){
        .token = name,
        .macro_close = close,
        .kind = CSANE_TYPE_HINT_TYPEDEF,
    };
    hints->count += 1;
}

bool
csane_type_hints_macro_typedef(CsaneTypeHints *hints, CsaneTokenView *view,
                               int32 close) {
    Tokenization *tokens = view->tokens;
    int32 open = csane_tokens_match(view, close);
    int32 name;

    if (hints == NULL || open < 0
        || !TOKEN_IS(&tokens->tokens[open], "(")) {
        return false;
    }
    name = csane_tokens_previous(view, open);
    if (name < view->range.first
        || !csane_token_macro_name(&tokens->tokens[name])) {
        return false;
    }
    for (int32 i = 0; i < hints->count; i += 1) {
        CsaneTypeHint *hint = &hints->items[i];
        CsaneTokenView alias;
        int32 a;
        int32 b;

        if (hint->kind != CSANE_TYPE_HINT_TYPEDEF
            || hint->macro_close < 0
            || !csane_tokens_view(&alias, tokens,
                                  (TokenRange){hint->token,
                                               hint->macro_close + 1})) {
            continue;
        }
        a = hint->token;
        b = name;
        while (a <= hint->macro_close && b <= close
               && tokens->tokens[a].len == tokens->tokens[b].len
               && !memcmp64(tokens->tokens[a].text,
                            tokens->tokens[b].text,
                            tokens->tokens[a].len)) {
            a = csane_tokens_next(&alias, a);
            b = csane_tokens_next(view, b);
        }
        if (a > hint->macro_close && b > close) {
            return true;
        }
    }
    return false;
}

static int32
csane_hint_alias_before(CsaneTokenView *view, int32 end) {
    Tokenization *tokens = view->tokens;
    int32 i = csane_tokens_previous(view, end);
    if (i < view->range.first) {
        return -1;
    }
    if (TOKEN_IS(&tokens->tokens[i], "]")) {
        int32 open = csane_tokens_match(view, i);
        if (open < 0) {
            return -1;
        }
        i = csane_tokens_previous(view, open);
    }
    if (i < view->range.first || tokens->tokens[i].kind != TOKEN_IDENT) {
        return -1;
    }
    return i;
}

/* Collect simple typedef declarators only. Complex function-pointer typedefs
 * are intentionally left unknown rather than guessed. */
static void
csane_hint_typedef(CsaneTypeHints *hints, CsaneTokenView *view,
                   int32 first) {
    Tokenization *tokens = view->tokens;
    int32 segment = csane_tokens_next(view, first);
    int32 i = segment;
    while (i >= view->range.first && i < view->range.end) {
        Token *token = &tokens->tokens[i];
        if (TOKEN_IS(token, "{") || TOKEN_IS(token, "(")
            || TOKEN_IS(token, "[")) {
            int32 close = csane_tokens_match(view, i);
            if (close < 0) {
                return;
            }
            i = csane_tokens_next(view, close);
            continue;
        }
        if (TOKEN_IS(token, ",") || TOKEN_IS(token, ";")) {
            int32 previous = csane_tokens_previous(view, i);
            int32 alias = csane_hint_alias_before(view, i);
            if (alias >= segment) {
                csane_hint_add(hints, alias, CSANE_TYPE_HINT_TYPEDEF);
            } else if (previous >= segment
                       && TOKEN_IS(&tokens->tokens[previous], ")")) {
                csane_hint_macro_typedef(hints, view, previous);
            }
            if (TOKEN_IS(token, ";")) {
                return;
            }
            segment = csane_tokens_next(view, i);
        }
        i = csane_tokens_next(view, i);
    }
    return;
}

void
csane_type_hints_init(CsaneTypeHints *hints, CsaneRegions *regions) {
    Tokenization *tokens = regions->tokens;

    *hints = (CsaneTypeHints){.tokens = regions->tokens};
    for (int32 i = 0; i < tokens->token_count; i += 1) {
        Token *token = &tokens->tokens[i];
        int32 region;
        CsaneTokenView view;
        if (token->kind != TOKEN_IDENT) {
            continue;
        }
        region = csane_regions_at_token(regions, i);
        if (region < 0
            || regions->items[region].kind != CSANE_REGION_CODE
            || !csane_tokens_view(&view, tokens,
                                  regions->items[region].tokens)) {
            continue;
        }
        if (csane_hint_aggregate(token)) {
            int32 name = csane_tokens_next(&view, i);
            if (name < view.range.end
                && tokens->tokens[name].kind == TOKEN_IDENT) {
                csane_hint_add(hints, name, CSANE_TYPE_HINT_TAG);
            }
        }
        if (csane_hint_word(token, STRLIT("typedef"))) {
            csane_hint_typedef(hints, &view, i);
        }
    }
    return;
}

void
csane_type_hints_free(CsaneTypeHints *hints) {
    if (hints == NULL) {
        return;
    }
    free2(hints->items, hints->capacity*SIZEOF(*hints->items));
    *hints = (CsaneTypeHints){0};
    return;
}

